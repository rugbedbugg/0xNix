#!/usr/bin/env python3
"""Compact wallpaper switcher.

usage: wallpaper-switcher DIR CURRENT APPLY-CMD

A strip of five thumbnails with the selected one, larger, in the middle,
its name underneath, and a prompt line. Tab/Shift+Tab, Left/Right (or
the scroll wheel) move, Home/End and Page Up/Down jump, typing filters by
name, Ctrl+R picks one at random, Shift+Enter applies and stays open, Enter
applies and closes, Esc clears the filter and then closes. Clicking a side
thumbnail selects it; clicking the middle one applies it.

Thumbnails are cached in $XDG_CACHE_HOME/wallpaper/thumbs, keyed by path,
size and mtime, generated by one worker thread (the visible ones first), and
only the visible ones are held in memory. Full-size images are never
decoded here: the desktop itself is the full-size preview (Shift+Enter).
"""

import hashlib
import math
import os
import random
import subprocess
import sys
import threading
from collections import OrderedDict, deque

import gi

gi.require_version("Gdk", "3.0")
gi.require_version("Gtk", "3.0")
gi.require_version("GdkPixbuf", "2.0")
gi.require_version("Pango", "1.0")
from gi.repository import Gdk, GdkPixbuf, GLib, Gtk, Pango  # noqa: E402

APP_ID = "wallpaper-switcher"
EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp", ".web", ".gif", ".bmp")
BIG = (256, 144)
SMALL = (160, 90)
SLOTS = 5
CSS = b"""
* { font-family: "VGA", monospace; font-size: 11pt; color: #ffffff; }
window { background: #20242c; }
.slot { border: 2px solid #444444; background: #000000; }
.slot.selected { border-color: #ffffff; }
.slot.empty { border-color: transparent; background: transparent; }
.dim { color: #8a8f99; }
"""


def cover(path, width, height):
    """Decode `path` scaled to cover width x height, center-cropped."""
    _, w, h = GdkPixbuf.Pixbuf.get_file_info(path)
    if not w or not h:
        raise GLib.Error("unreadable image")
    scale = max(width / w, height / h)
    sw, sh = max(width, math.ceil(w * scale)), max(height, math.ceil(h * scale))
    pixbuf = GdkPixbuf.Pixbuf.new_from_file_at_scale(path, sw, sh, False)
    x, y = (pixbuf.get_width() - width) // 2, (pixbuf.get_height() - height) // 2
    return pixbuf.new_subpixbuf(x, y, width, height).copy()


class Thumbs:
    """Disk-cached thumbnails, generated by one worker thread."""

    def __init__(self, on_ready):
        cache = os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")
        self.dir = os.path.join(cache, "wallpaper", "thumbs")
        os.makedirs(self.dir, exist_ok=True)
        self.on_ready = on_ready
        self.memory = OrderedDict()
        self.urgent = deque()
        self.backlog = deque()
        self.keep = None
        self.wake = threading.Condition()
        threading.Thread(target=self.work, daemon=True).start()

    def file(self, path):
        st = os.stat(path)
        key = f"{path}\0{st.st_size}\0{st.st_mtime_ns}\0{BIG}".encode()
        return os.path.join(self.dir, hashlib.sha1(key).hexdigest() + ".png")

    def get(self, path):
        """(big, small) thumbnails if ready, else None (queued urgently)."""
        if path in self.memory:
            self.memory.move_to_end(path)
            return self.memory[path]
        try:
            big = GdkPixbuf.Pixbuf.new_from_file(self.file(path))
        except (GLib.Error, OSError):
            with self.wake:
                self.urgent.append(path)
                self.wake.notify()
            return None
        pair = (big, big.scale_simple(*SMALL, GdkPixbuf.InterpType.BILINEAR))
        self.memory[path] = pair
        while len(self.memory) > 4 * SLOTS:
            self.memory.popitem(last=False)
        return pair

    def fill(self, paths):
        """Generate every missing thumbnail in the background, in order,
        then delete cached ones no current wallpaper maps to (removed or
        changed files, an older thumbnail size)."""
        with self.wake:
            self.backlog.extend(paths)
            self.keep = list(paths)
            self.wake.notify()

    def prune(self, paths):
        try:
            wanted = {os.path.basename(self.file(p)) for p in paths}
            for name in os.listdir(self.dir):
                if name not in wanted:
                    os.remove(os.path.join(self.dir, name))
        except OSError:
            pass

    def work(self):
        while True:
            with self.wake:
                while not self.urgent and not self.backlog and self.keep is None:
                    self.wake.wait()
                if self.urgent or self.backlog:
                    path, keep = (self.urgent or self.backlog).popleft(), None
                else:
                    path, keep, self.keep = None, self.keep, None
            if keep is not None:
                self.prune(keep)
                continue
            try:
                out = self.file(path)
                if os.path.exists(out):
                    continue
                cover(path, *BIG).savev(out + ".tmp", "png", [], [])
                os.replace(out + ".tmp", out)
            except (GLib.Error, OSError):
                continue
            GLib.idle_add(self.on_ready, path)


class Switcher(Gtk.Box):
    def __init__(self, directory, current, apply_cmd, close):
        super().__init__(orientation=Gtk.Orientation.VERTICAL, spacing=8)
        self.apply_cmd = apply_cmd
        self.close = close
        self.paths = sorted(
            (
                os.path.join(directory, name)
                for name in os.listdir(directory)
                if name.lower().endswith(EXTENSIONS)
                and os.path.isfile(os.path.join(directory, name))
                and not os.path.islink(os.path.join(directory, name))
            ),
            key=lambda p: os.path.basename(p).lower(),
        )
        self.shown = list(self.paths)
        self.query = ""
        self.index = self.shown.index(current) if current in self.shown else 0
        self.scroll_dx = 0.0
        self.thumbs = Thumbs(self.thumb_ready)

        for side in ("top", "bottom", "start", "end"):
            getattr(self, f"set_margin_{side}")(16)

        strip = Gtk.Box(spacing=12)
        strip.set_halign(Gtk.Align.CENTER)
        self.slots = []
        for offset in range(-(SLOTS // 2), SLOTS // 2 + 1):
            image = Gtk.Image()
            image.set_size_request(*(BIG if offset == 0 else SMALL))
            box = Gtk.Box()
            box.get_style_context().add_class("slot")
            box.add(image)
            events = Gtk.EventBox()
            events.set_valign(Gtk.Align.CENTER)
            events.add(box)
            events.connect("button-press-event", self.slot_clicked, offset)
            strip.pack_start(events, False, False, 0)
            self.slots.append((offset, box, image))
        self.pack_start(strip, False, False, 0)

        self.name = Gtk.Label()
        self.name.set_ellipsize(Pango.EllipsizeMode.MIDDLE)
        self.name.set_max_width_chars(60)
        self.pack_start(self.name, False, False, 0)

        status = Gtk.Box()
        self.prompt = Gtk.Label(xalign=0)
        self.count = Gtk.Label(xalign=1)
        self.count.get_style_context().add_class("dim")
        status.pack_start(self.prompt, True, True, 0)
        status.pack_end(self.count, False, False, 0)
        self.pack_start(status, False, False, 0)

        self.thumbs.fill(self.paths[self.index :] + self.paths[: self.index])
        self.refresh()

    # -- state -------------------------------------------------------------

    def selected(self):
        return self.shown[self.index] if self.shown else None

    def move(self, delta):
        if self.shown:
            self.index = max(0, min(len(self.shown) - 1, self.index + delta))
            self.refresh()

    def jump_random(self):
        if len(self.shown) > 1:
            self.index = random.choice([i for i in range(len(self.shown)) if i != self.index])
            self.refresh()

    def set_query(self, query):
        keep = self.selected()
        self.query = query
        terms = query.lower().split()
        self.shown = [p for p in self.paths if all(t in os.path.basename(p).lower() for t in terms)]
        self.index = self.shown.index(keep) if keep in self.shown else 0
        self.refresh()

    def apply(self, close):
        path = self.selected()
        if path:
            subprocess.Popen([self.apply_cmd, "set", path])
            if close:
                self.close()

    # -- drawing -----------------------------------------------------------

    def refresh(self):
        path = self.selected()
        self.prompt.set_text(f"Wallpaper: {self.query}_")
        self.count.set_text(f"{self.index + 1} / {len(self.shown)}" if self.shown else "0 / 0")
        self.name.set_text(os.path.basename(path) if path else "no match")
        for offset, box, image in self.slots:
            i = self.index + offset
            style = box.get_style_context()
            style.remove_class("selected")
            if not self.shown or not 0 <= i < len(self.shown):
                style.add_class("empty")
                image.clear()
                continue
            style.remove_class("empty")
            if offset == 0:
                style.add_class("selected")
            pair = self.thumbs.get(self.shown[i])
            if pair:
                image.set_from_pixbuf(pair[0] if offset == 0 else pair[1])
            else:
                image.clear()

    def thumb_ready(self, path):
        visible = {self.shown[self.index + o] for o, _, _ in self.slots if 0 <= self.index + o < len(self.shown)}
        if path in visible:
            self.refresh()
        return False

    # -- input -------------------------------------------------------------

    def slot_clicked(self, _widget, _event, offset):
        if offset == 0:
            self.apply(close=True)
        else:
            self.move(offset)

    def on_key(self, _window, event):
        key, state = event.keyval, event.state
        ctrl = state & Gdk.ModifierType.CONTROL_MASK
        if key == Gdk.KEY_Escape:
            if self.query:
                self.set_query("")
            else:
                self.close()
        elif key in (Gdk.KEY_Return, Gdk.KEY_KP_Enter):
            self.apply(close=not state & Gdk.ModifierType.SHIFT_MASK)
        # Shift+Tab arrives as ISO_Left_Tab (with Shift still set).
        elif key in (Gdk.KEY_Left, Gdk.KEY_Up, Gdk.KEY_ISO_Left_Tab) or (
            key == Gdk.KEY_Tab and state & Gdk.ModifierType.SHIFT_MASK
        ):
            self.move(-1)
        elif key in (Gdk.KEY_Right, Gdk.KEY_Down, Gdk.KEY_Tab):
            self.move(1)
        elif key == Gdk.KEY_Page_Up:
            self.move(-SLOTS)
        elif key == Gdk.KEY_Page_Down:
            self.move(SLOTS)
        elif key == Gdk.KEY_Home:
            self.move(-len(self.shown))
        elif key == Gdk.KEY_End:
            self.move(len(self.shown))
        elif key == Gdk.KEY_BackSpace:
            self.set_query("" if ctrl else self.query[:-1])
        elif ctrl and key in (Gdk.KEY_r, Gdk.KEY_R):
            self.jump_random()
        elif ctrl and key in (Gdk.KEY_u, Gdk.KEY_U):
            self.set_query("")
        else:
            char = chr(Gdk.keyval_to_unicode(key) or 0)
            if char.isprintable() and char and not ctrl:
                self.set_query(self.query + char)
            else:
                return False
        return True

    def on_scroll(self, _window, event):
        if event.direction in (Gdk.ScrollDirection.UP, Gdk.ScrollDirection.LEFT):
            self.move(-1)
        elif event.direction in (Gdk.ScrollDirection.DOWN, Gdk.ScrollDirection.RIGHT):
            self.move(1)
        elif event.direction == Gdk.ScrollDirection.SMOOTH:
            _, dx, dy = event.get_scroll_deltas()
            self.scroll_dx += dx + dy
            while abs(self.scroll_dx) >= 1:
                step = 1 if self.scroll_dx > 0 else -1
                self.scroll_dx -= step
                self.move(step)
        return True


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: wallpaper-switcher DIR CURRENT APPLY-CMD")
    directory, current, apply_cmd = sys.argv[1:]
    directory = os.path.realpath(directory)

    # The Wayland app-id Hyprland's window rules match on.
    GLib.set_prgname(APP_ID)
    Gdk.set_program_class(APP_ID)

    provider = Gtk.CssProvider()
    provider.load_from_data(CSS)
    Gtk.StyleContext.add_provider_for_screen(
        Gdk.Screen.get_default(), provider, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION
    )

    window = Gtk.Window(title="Wallpaper")
    window.set_decorated(False)
    window.set_resizable(False)
    window.add_events(Gdk.EventMask.SCROLL_MASK | Gdk.EventMask.SMOOTH_SCROLL_MASK)
    switcher = Switcher(directory, os.path.realpath(current) if current else "", apply_cmd, window.destroy)
    window.add(switcher)
    window.connect("key-press-event", switcher.on_key)
    window.connect("scroll-event", switcher.on_scroll)
    window.connect("destroy", Gtk.main_quit)
    window.show_all()
    Gtk.main()


if __name__ == "__main__":
    main()
